test('update --check lists what would change and writes nothing', (t) => {
  const root = fixture(t);
  const result = setup(root, { hosts: ['codex'] });
  assert.equal(update(root, { check: true }).plan.current, true);

  const stale = result.added[0];
  makeStale(root, stale);
  const before = snapshot(root);
  const { plan } = update(root, { check: true });
  assert.deepEqual(plan.changed, [stale]);
  assert.equal(plan.current, false);
  assert.equal(plan.blocked, false);
  assert.equal(plan.files, undefined, 'the public plan carries no contents');
  assert.deepEqual(snapshot(root), before);
});

test('update with nothing to do writes nothing', (t) => {
  const root = fixture(t);
  setup(root, { hosts: ['codex'] });
  const manifest = path.join(root, GENERATED_MANIFEST);
  const earlier = new Date(Math.floor(Date.now() / 1000) * 1000 - 60_000);
  fs.utimesSync(manifest, earlier, earlier);

  const result = update(root);
  assert.deepEqual([...result.added, ...result.changed, ...result.removed], []);
  assert.equal(fs.statSync(manifest).mtimeMs, earlier.getTime(), 'the manifest is not rewritten');
});

