/**
 * Make one generated file stale the way a toolkit change does: the file and its
 * manifest digest agree, but neither matches what would be generated now.
 */
function makeStale(root, relative) {
  fs.writeFileSync(path.join(root, relative), 'generated by an older toolkit\n', 'utf8');
  const manifestFile = path.join(root, GENERATED_MANIFEST);
  const manifest = JSON.parse(fs.readFileSync(manifestFile, 'utf8'));
  manifest.files[relative] = digest('generated by an older toolkit\n');
  fs.writeFileSync(manifestFile, `${JSON.stringify(manifest, null, 2)}\n`, 'utf8');
}

/** Every file under root, with its content, for proving nothing was written. */
function snapshot(root) {
  /** @type {Record<string, string>} */
  const files = {};
  for (const entry of fs.readdirSync(root, { recursive: true, withFileTypes: true })) {
    if (!entry.isFile()) continue;
    const full = path.join(entry.parentPath, entry.name);
    files[path.relative(root, full)] = fs.readFileSync(full, 'utf8');
  }
  return files;
}

test('update refuses as a whole when a generated file was modified, and applies when it is forced', (t) => {
  const root = fixture(t);
  const result = setup(root, { hosts: ['codex'] });
  const [target, stale] = result.added;
  makeStale(root, stale);
  fs.writeFileSync(path.join(root, target), 'edited by hand\n', 'utf8');
  const before = snapshot(root);

  assert.throws(() => update(root), (error) => /nothing was written/.test(error.message) && error.message.includes(target));
  assert.deepEqual(snapshot(root), before, 'a refused update writes nothing, not even the stale file it could have fixed');

  const forced = update(root, { force: [target] });
  assert.deepEqual(forced.changed.sort(), [target, stale].sort());
  assert.notEqual(fs.readFileSync(path.join(root, target), 'utf8'), 'edited by hand\n');
});

test('a file of yours at a generated path refuses setup, and is replaced only when named', (t) => {
  const root = fixture(t);
  const planned = setup(root, { hosts: ['codex'] });
  const target = planned.added[0];
  remove(root);

  fs.mkdirSync(path.dirname(path.join(root, target)), { recursive: true });
  fs.writeFileSync(path.join(root, target), 'mine\n', 'utf8');

  assert.throws(() => setup(root, { hosts: ['codex'] }), (error) => error.message.includes(`${target} (yours`));
  assert.equal(fs.readFileSync(path.join(root, target), 'utf8'), 'mine\n');
  assert.ok(!fs.existsSync(path.join(root, GENERATED_MANIFEST)), 'a refused setup writes no manifest');

  const forced = setup(root, { hosts: ['codex'], force: [target] });
  assert.ok(forced.changed.includes(target));
  assert.notEqual(fs.readFileSync(path.join(root, target), 'utf8'), 'mine\n');
});

test('a file that already holds what would be generated is adopted, not refused', (t) => {
  const root = fixture(t);
  setup(root, { hosts: ['codex'] });
  fs.rmSync(path.join(root, GENERATED_MANIFEST));

  const result = update(root);
  assert.deepEqual(result.added, []);
  assert.deepEqual(result.changed, []);
  assert.ok(result.unchanged.length > 0);
  assert.equal(result.manifest, 'added', 'writing the manifest is reported, since it has to be committed');
  assert.ok(fs.existsSync(path.join(root, GENERATED_MANIFEST)));
});

test('update reports the manifest whenever it rewrites it', (t) => {
  const root = fixture(t);
  const result = setup(root, { hosts: ['codex'] });
  assert.equal(result.manifest, 'added');

  makeStale(root, result.added[0]);
  assert.equal(update(root).manifest, 'changed');
  assert.equal(update(root).manifest, null);
});

test('a write that fails partway leaves files a second update finishes', (t) => {
  const root = fixture(t);
  const result = setup(root, { hosts: ['codex'] });
  const [first, second] = result.added;
  makeStale(root, first);
  makeStale(root, second);

  const original = fs.writeFileSync;
  let calls = 0;
  fs.writeFileSync = (...args) => {
    calls += 1;
    if (calls === 2) throw new Error('disk full');
    return original(...args);
  };
  try {
    assert.throws(() => update(root), /disk full/);
  } finally {
    fs.writeFileSync = original;
  }
  assert.notEqual(fs.readFileSync(path.join(root, first), 'utf8'), 'generated by an older toolkit\n', 'precondition: the first write landed');
  assert.equal(fs.readFileSync(path.join(root, second), 'utf8'), 'generated by an older toolkit\n', 'precondition: the second did not');

  const again = update(root);
  assert.deepEqual(again.changed, [second]);
  assert.ok(again.unchanged.includes(first), 'the file written before the failure is adopted, not refused');
  assert.equal(update(root, { check: true }).plan.current, true);
});

